// Copies the bundled (offline) web fonts into public/fonts and writes fonts.css + fonts.json.
// Fonts are self-hosted so the app (and PDF rendering) never needs internet access.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const list = require('../shared/fontlist.json');
const out = path.join(root, 'public', 'fonts');
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

const WEIGHTS = [400, 500, 600, 700];
let css = '/* generated by scripts/build-assets.js */\n';
const manifest = {};
for (const f of list) {
  const dir = path.join(root, 'node_modules', '@fontsource', f.pkg, 'files');
  manifest[f.name] = [];
  for (const style of ['normal', 'italic']) {
    for (const w of WEIGHTS) {
      if (style === 'italic' && w !== 400 && w !== 700) continue;
      const file = `${f.pkg}-latin-${w}-${style}.woff2`;
      if (!fs.existsSync(path.join(dir, file))) continue;
      fs.copyFileSync(path.join(dir, file), path.join(out, file));
      manifest[f.name].push({ weight: w, style, file });
      css += `@font-face{font-family:'${f.name}';font-style:${style};font-weight:${w};font-display:swap;src:url(/fonts/${file}) format('woff2');}\n`;
    }
  }
  if (!manifest[f.name].length) throw new Error('No font files found for ' + f.name);
}
fs.writeFileSync(path.join(out, 'fonts.css'), css);
fs.writeFileSync(path.join(out, 'fonts.json'), JSON.stringify(manifest, null, 1));
console.log(`Fonts built: ${list.length} families, ${fs.readdirSync(out).length - 2} files`);
